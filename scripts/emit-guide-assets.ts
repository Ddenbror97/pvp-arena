import { build } from "esbuild";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const guidesDir = resolve(root, "src/content/guides");
const outDir = resolve(root, "public/guide-bodies");
const catalogPath = resolve(guidesDir, "catalog.generated.ts");
const stampPath = resolve(root, "node_modules/.cache/guide-assets.stamp");
const bundlePath = resolve(root, "node_modules/.cache/pvp-guide-index.mjs");

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

type SourceGuide = {
  slug: string;
  cluster: string;
  pillar?: boolean;
  keyword: string;
  title: string;
  h1: string;
  description: string;
  updated: string;
};

function stamp(): string {
  const names = readdirSync(guidesDir).filter(
    (name) => name.endsWith(".ts") && name !== "catalog.generated.ts",
  );
  let max = 0;
  let bytes = 0;
  for (const name of names) {
    const stat = statSync(resolve(guidesDir, name));
    if (stat.mtimeMs > max) max = stat.mtimeMs;
    bytes += stat.size;
  }
  return `${names.length}:${bytes}:${Math.round(max)}`;
}

/** Write one JSON file per guide plus a slim catalog. The Worker imports the catalog, not the bodies. */
export async function emitGuideAssets(): Promise<{ guides: number; skipped: boolean }> {
  const next = stamp();
  if (
    existsSync(stampPath) &&
    existsSync(catalogPath) &&
    existsSync(outDir) &&
    readFileSync(stampPath, "utf8") === next
  ) {
    return { guides: 0, skipped: true };
  }

  mkdirSync(dirname(bundlePath), { recursive: true });
  await build({
    absWorkingDir: root,
    entryPoints: [resolve(guidesDir, "index.ts")],
    bundle: true,
    format: "esm",
    platform: "node",
    outfile: bundlePath,
    logLevel: "silent",
  });
  const mod = (await import(`${pathToFileURL(bundlePath).href}?v=${Date.now()}`)) as {
    GUIDES: SourceGuide[];
  };

  mkdirSync(outDir, { recursive: true });
  const metas = mod.GUIDES.map((guide) => {
    if (!SLUG.test(guide.slug))
      throw new Error(`guide slug is not a safe file name: ${guide.slug}`);
    writeFileSync(resolve(outDir, `${guide.slug}.json`), JSON.stringify(guide));
    return {
      slug: guide.slug,
      cluster: guide.cluster,
      pillar: guide.pillar === true,
      keyword: guide.keyword,
      title: guide.title,
      h1: guide.h1,
      description: guide.description,
      updated: guide.updated,
    };
  });

  const source = `/* Generated by scripts/emit-guide-assets.ts. Do not edit. */
import type { GuideCluster } from "./types";

export type GuideMeta = {
  slug: string;
  cluster: GuideCluster;
  pillar: boolean;
  keyword: string;
  title: string;
  h1: string;
  description: string;
  updated: string;
};

export const GUIDE_META: GuideMeta[] = ${JSON.stringify(metas)};
`;
  writeFileSync(catalogPath, source);
  mkdirSync(dirname(stampPath), { recursive: true });
  writeFileSync(stampPath, next);
  return { guides: metas.length, skipped: false };
}

const invoked =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  emitGuideAssets()
    .then((result) => {
      console.log(
        result.skipped ? "guide assets unchanged" : `wrote ${result.guides} guide assets`,
      );
    })
    .catch((error: unknown) => {
      console.error(error);
      process.exit(1);
    });
}

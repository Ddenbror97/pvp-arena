#!/usr/bin/env python3
"""The strait coast road's motor court made enterable (owner, 2026-11-12: the Modular Motel
download, "see if those work"; standing rule: new buildings enterable, with opening doors).
Modular Motel (Wardster, CC BY), measured from its processed LOD0 (wall planes, up-facing
surfaces and voxel collision, 2026-11-12), model-local metres, fronts to +z:

- a reception cabin, x -11.89..-5.39, z -5.08..-1.58, its door in the front wall at x -7.88..
  -6.88 and a corner window at its front-west corner, under a carport canopy that runs on to
  z 5.47 on a V post (the canopy's underside at 2.7 m, the MOTEL sign on its west edge);
- a cabin block, x 1.95..11.88, z -4.97..2.03, two rooms side by side, each with its door
  (x 2.99..3.92 and 7.71..8.65, set 0.17 m into the front wall) and a window beside it;
- single storey: the doors' sills at 0.1 m, their heads at 2.02, the ceilings' planes at 2.10.

The walls are single-sided planes (from inside, a room looked out through them), so each room
(the reception and the two cabin rooms) is cut clear inside, gets a floor at the sills' level,
plaster liners just inside the shell (partitioned between the two rooms), a ceiling, and its
own fitted door in the painted door's place. The reception gets a counter; the canopy a pump
island (its two fuel dispensers are placed by layout.ts straitRoadside).

Writes art/br/building-access-v18.json (applied by repair_building_access.mjs on top of the
motorcourt-v1 revision) and its walks to art/br/building-access-routes.json.

    python3 -I art/br/fitout/motorcourt.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kit import box, cut_x, door, room_ceiling, room_liners  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PLASTER = [0.84, 0.81, 0.72]
FLOOR = [0.45, 0.37, 0.3]
CONCRETE = [0.62, 0.61, 0.58]
WOOD = [0.42, 0.29, 0.19]

FL = 0.1  # the floor (the doors' sills)
CEIL = 2.04  # the ceiling liners' underside (the drawn ceiling is at 2.10)
DOOR_TOP = 2.02

# Rooms (x0, x1, z0, z1) inside the shell, and each one's door (centre x, the wall's outer face z,
# width): the front walls' doors sit 0.17 m in, the liners stop short of them.
CABIN = [
    ((1.98, 6.915, -4.85, 1.70), (3.455, 2.03, 0.93)),
    ((6.915, 11.85, -4.85, 1.70), (8.18, 2.03, 0.94)),
]
RECEPTION = ((-11.85, -5.43, -4.85, -1.92), (-7.385, -1.58, 1.0))
ROOMS = CABIN + [RECEPTION]

doors, cuts, floors, walls, rects, gaps = [], [], [], [], [], []
for (x0, x1, z0, z1), (dx, face, width) in ROOMS:
    rects.append((x0, x1, z0, z1))
    doors.append(door(dx, (z1 + face) / 2, FL, DOOR_TOP, "x", width))
    # The doorway through the painted door and the shell's voxels (0.3 m proud of the face).
    cuts.append(cut_x(dx, z1 - 0.15, face + 0.32, FL, DOOR_TOP, width))
    # Everything inside the room cut away up to the drawn ceiling.
    cuts.append(box(x0 + 0.02, FL + 0.01, z0 + 0.02, x1 - 0.02, 2.4, z1 - 0.02))
    floors.append(box(x0, FL - 0.3, z0, x1, FL, z1))
    gaps.append((dx, z1, width + 0.15, DOOR_TOP - FL + 0.05))
# Liners round each room on its own (the two cabin rooms' meet back to back: shut off from each
# other), then the ceilings.
for rect in rects:
    walls += room_liners([rect], FL, CEIL, [g for g in gaps if rect[0] <= g[0] <= rect[1]])
ceilings = room_ceiling(rects, CEIL + 0.15)

# The reception's counter along its back-west corner, clear of the door's path.
counter = [box(-11.0, FL, -3.0, -9.4, FL + 0.95, -2.45)]
# The canopy's concrete apron (3 cm proud of the ground) and the pump island on it (a kerb
# 0.15 m high), west of the reception's door; its two dispensers stand at x -10.35 and -8.85
# on the island's top, 0.18 m (layout.ts).
apron = [box(-11.95, -0.3, -1.55, -5.35, 0.03, 5.47)]
island = [box(-11.1, 0.03, 1.45, -8.1, 0.18, 2.75)]

models = {
    "modular-motel": {
        "doors": doors,
        "cuts": cuts,
        "floors": floors,
        "groups": [
            {"name": "Rooms' walls and ceilings", "color": PLASTER, "boxes": walls + ceilings},
            {"name": "Reception counter", "color": WOOD, "boxes": counter},
            {"name": "Canopy apron and pump island", "color": CONCRETE, "boxes": apron + island},
        ],
        "color": FLOOR,
    }
}

spec = {
    "version": "access-v18",
    "baseManifest": "models.motorcourt-v1.json",
    "baseCollision": "collision.motorcourt-v1.json",
    "notes": "The strait coast road's motor court enterable: the reception and the cabin block's "
    "two rooms, each with its fitted door; the canopy's pump island. Generated by "
    "art/br/fitout/motorcourt.py.",
    "models": models,
}
out = ROOT / "building-access-v18.json"
out.write_text(json.dumps(spec, indent=1) + "\n")

# Walks from the forecourt (the canopy's front at z 5.47) into each room.
ROUTES = [
    ["modular-motel", [[3.455, 6.5], [3.455, 3.0], [3.455, 0.8], [4.6, -2.5]]],
    ["modular-motel", [[8.18, 6.5], [8.18, 3.0], [8.18, 0.8], [9.6, -2.5]]],
    ["modular-motel", [[-6.4, 7.5], [-6.4, 0.2], [-7.385, -0.6], [-7.385, -2.6], [-8.6, -3.8]]],
]
routes_file = ROOT / "building-access-routes.json"
routes = [r for r in json.loads(routes_file.read_text()) if r[0] not in {m for m, _ in ROUTES}]
routes_file.write_text(json.dumps(routes + ROUTES, indent=2) + "\n")
print(out, len(ROUTES), "routes")

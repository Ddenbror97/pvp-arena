#!/usr/bin/env python3
"""The highway stops' filling station made enterable (owner, 2026-11-12: "audit the rest of the
map if any gas station / motel can be placed out along the road"; standing rule: new buildings
enterable, with opening doors). Abandoned Gas Station (kand8998, CC BY), measured from its
processed LOD0 (wall planes, up-facing surfaces and voxel collision, 2026-11-12), model-local
metres, its front (shop door, pumps) to +z:

- the shop, x -5.82..5.88, z -8.4..3.0 (walls 0.3 m), on a sidewalk pad whose top is 0.33 m up;
  its door in the front wall at x -1.92..-0.12, the shop windows either side above 1.8 m;
- a tyre bay's roll-up door shut in the east wall (x 4.98..5.28, z -6.6..-0.3);
- the flat roof running on to z 8.7 over the pump island (its top 0.34 m up, two pumps).

The painted door's head is 1.6 m over the sill, under a 1.8 m player: the doorway is cut 2.0 m
tall (the fitted door covers the wall up to it). The shop is cut clear inside, floored at the
sill, lined, ceiled at 3.0 m (the shell's own ceilings and fittings, 2.1 and 3.1 m up, cut
away) and given a counter.

Writes art/br/building-access-v19.json (applied by repair_building_access.mjs on top of the
highway-v1 revision) and its walks to art/br/building-access-routes.json.

    python3 -I art/br/fitout/highway.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kit import box, cut_x, door, room_ceiling, room_liners  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
PLASTER = [0.82, 0.8, 0.74]
TILE = [0.55, 0.53, 0.5]
WOOD = [0.42, 0.29, 0.19]

FL = 0.33  # the shop's floor (the pad's top, the door's sill)
CEIL = 3.0
DOOR_X, DOOR_W, DOOR_TOP = -1.02, 1.7, FL + 2.0
FACE = 2.76  # the front wall's outer face
SHOP = (-5.45, 4.9, -8.05, 2.25)

x0, x1, z0, z1 = SHOP
doors = [door(DOOR_X, (z1 + FACE) / 2, FL, DOOR_TOP, "x", DOOR_W)]
cuts = [
    # The doorway through the door's recess and the wall (its voxels 0.24 m proud).
    cut_x(DOOR_X, z1 - 0.15, FACE + 0.3, FL, DOOR_TOP, DOOR_W),
    # Everything inside cut away up to the roof's underside.
    box(x0 + 0.02, FL + 0.01, z0 + 0.02, x1 - 0.02, 4.3, z1 - 0.02),
]
floors = [box(x0, FL - 0.3, z0, x1, FL, z1)]
walls = room_liners([SHOP], FL, CEIL, [(DOOR_X, z1, DOOR_W + 0.15, DOOR_TOP - FL + 0.05)])
ceiling = room_ceiling([SHOP], CEIL + 0.15)
# The till counter along the west wall, clear of the door.
counter = [box(-5.3, FL, -2.6, -4.6, FL + 0.95, 0.9)]


def pad_boxes(cell=0.25):
    """The sidewalk round the shop's front and sides and the pump island, exact (their tops at
    0.33-0.34 m): the up-facing triangles at that height rasterised in `cell` squares and merged
    into strips (voxelised they stood 0.6 m, over the 0.35 m a player steps up)."""
    tris = json.loads((ROOT / "fitout" / "highway-pad.json").read_text())

    def inside(px, pz, t):
        (ax, az), (bx, bz), (cx, cz) = t
        d1 = (px - bx) * (az - bz) - (ax - bx) * (pz - bz)
        d2 = (px - cx) * (bz - cz) - (bx - cx) * (pz - cz)
        d3 = (px - ax) * (cz - az) - (cx - ax) * (pz - az)
        return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))

    xs = [p[0] for t in tris for p in t]
    zs = [p[1] for t in tris for p in t]
    x0, z0 = min(xs), min(zs)
    nx, nz = int((max(xs) - x0) / cell) + 1, int((max(zs) - z0) / cell) + 1
    boxes = []
    for j in range(nz):
        pz = z0 + (j + 0.5) * cell
        run = None
        for i in range(nx + 1):
            hit = i < nx and any(inside(x0 + (i + 0.5) * cell, pz, t) for t in tris)
            if hit and run is None:
                run = i
            if not hit and run is not None:
                boxes.append(box(x0 + run * cell, 0.0, z0 + j * cell, x0 + i * cell, FL, z0 + (j + 1) * cell))
                run = None
    return boxes


# The pad's and island's voxels cleared outside the shop's walls (inside, the room's cut).
clear = [
    box(-6.5, -0.1, -4.9, -5.83, 0.62, 3.95),
    box(-6.5, -0.1, 3.01, 6.5, 0.62, 3.95),
    box(5.89, -0.1, -0.4, 6.5, 0.62, 3.95),
    box(-4.1, -0.1, 6.85, 4.1, 0.62, 8.45),
]

models = {
    "roadside-gas": {
        "doors": doors,
        "cuts": cuts,
        "floors": floors,
        "clear": clear,
        "solid": pad_boxes(),
        "groups": [
            {"name": "Shop's walls and ceiling", "color": PLASTER, "boxes": walls + ceiling},
            {"name": "Till counter", "color": WOOD, "boxes": counter},
        ],
        "color": TILE,
    }
}
spec = {
    "version": "access-v19",
    "baseManifest": "models.highway-v1.json",
    "baseCollision": "collision.highway-v1.json",
    "notes": "The highway stops' filling station enterable: its shop through a 2 m doorway with "
    "its fitted door. Generated by art/br/fitout/highway.py.",
    "models": models,
}
out = ROOT / "building-access-v19.json"
out.write_text(json.dumps(spec, indent=1) + "\n")

# From the forecourt round the pump island's west end, under the roof, up the sidewalk and
# through the door to the back of the shop.
ROUTES = [
    [
        "roadside-gas",
        [[-7.5, 11.5], [-7.5, 5.2], [-2.6, 4.6], [DOOR_X, 4.6], [DOOR_X, 3.3], [DOOR_X, 1.0], [-2.0, -5.5]],
    ],
]
routes_file = ROOT / "building-access-routes.json"
routes = [r for r in json.loads(routes_file.read_text()) if r[0] not in {m for m, _ in ROUTES}]
routes_file.write_text(json.dumps(routes + ROUTES, indent=2) + "\n")
print(out, len(ROUTES), "routes")

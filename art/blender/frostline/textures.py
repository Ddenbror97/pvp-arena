"""
Procedural PBR textures for FROSTLINE (deterministic, seeded).

  python3 art/blender/frostline/textures.py     # writes art/blender/frostline/build/tex/*.png

Same conventions and helpers as the AIM ARENA's textures (art/blender/map/textures.py, imported
here): every texture tiles seamlessly; albedo sRGB; *_n OpenGL tangent-space normals; *_r linear
roughness; low-frequency maps at 512 px. The shared industrial set (corrugated metal, crate wood,
canvas, hazard stencil, PVPSPINARENA banners from the official logo) is generated by the same
functions; the winter set (snow, ice, Soviet concrete, PO-2 fence panels, painted steel, lit
windows, pines, mountains, festive bulbs) is new. `lightpool` is a baked warm-light map for the
ground (second UV set), so lamps light the snow without real-time lights.
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "map"))
import textures as T  # noqa: E402  (AIM ARENA texture helpers)

OUT = os.path.join(HERE, "build", "tex")
T.OUT = OUT
T.HALF |= {"snow_n", "snowpack_r", "soviet_r", "fence_r", "steel_paint_n", "steel_paint_r", "ice_r", "mountain_n",
           "pine_bark_n", "pine_n", "pine", "fence", "mountain", "ice", "ice_n", "canvas", "snow_r", "pine_bark",
           "steel_paint_r", "snowpack_r", "tarp_n", "snowpack_n", "fence_n"}
noise, normal_from_height, save, tint = T.noise, T.normal_from_height, T.save, T.tint


def sparkle(n, seed):
    r = np.random.default_rng(seed)
    s = np.zeros((n, n))
    idx = r.integers(0, n, (n * n // 180, 2))
    s[idx[:, 0], idx[:, 1]] = r.random(len(idx))
    return s


def snow():
    """Fresh snow: drifts, caps, roofs. Soft wind ripples, faint blue shadowing, sparkle in roughness."""
    n = 1024
    soft = noise(n, 6, 3, seed=201)
    ripple = noise(n, 5, 12, seed=202)
    fine = noise(n, 7, 48, seed=203)
    h = soft * 0.7 + ripple * 0.25 + fine * 0.05
    g = 0.86 + 0.07 * soft + 0.03 * fine
    base = np.dstack([g * 0.955, g * 0.975, g * 1.0])
    save("snow", base)
    save("snow_n", normal_from_height(h, 2.2))
    save("snow_r", np.clip(0.82 + 0.08 * fine - 0.35 * sparkle(n, 204), 0.3, 1))


def snowpack():
    """Trodden ground: packed snow with slush tracks, wet ice and patches of exposed asphalt."""
    n = 1024
    m = noise(n, 6, 3, seed=211)
    fine = noise(n, 7, 40, seed=212)
    y, x = np.mgrid[0:n, 0:n] / n
    # Wheel/boot tracks: soft parallel bands along the tile, warped by noise.
    warp = noise(n, 3, 2, seed=213) * 0.25
    tracks = np.clip(1 - np.abs(((y + warp) * 2) % 1 - 0.5) / 0.07, 0, 1) * np.clip(
        (noise(n, 4, 6, seed=214) - 0.45) * 3, 0, 1) * 0.55
    slush = np.clip((noise(n, 5, 5, seed=215) - 0.55) * 4, 0, 1)
    asphalt = np.clip((noise(n, 5, 6, seed=216) - 0.70) * 6, 0, 1)
    ice = np.clip((noise(n, 4, 4, seed=217) - 0.6) * 5, 0, 1) * (1 - asphalt)
    snowc = np.array([0.80, 0.83, 0.87]) * (0.92 + 0.10 * m + 0.04 * fine)[..., None]
    slushc = np.array([0.50, 0.52, 0.55]) * (0.9 + 0.2 * fine)[..., None]
    asphc = np.array([0.15, 0.15, 0.16]) * (0.8 + 0.4 * fine)[..., None]
    wet = np.clip(tracks * 0.6 + slush * 0.8, 0, 1)
    base = snowc * (1 - wet[..., None]) + slushc * wet[..., None]
    base = base * (1 - asphalt[..., None]) + asphc * asphalt[..., None]
    base = base * (1 - 0.15 * ice[..., None]) + np.array([0.70, 0.78, 0.86]) * 0.15 * ice[..., None]
    save("snowpack", base)
    save("snowpack_n", normal_from_height(m * 0.5 + fine * 0.15 - tracks * 0.35 - asphalt * 0.2, 3.0))
    # Ice and wet slush are glossy (not mirrors), snow and asphalt rough.
    save("snowpack_r", np.clip(0.86 - 0.42 * ice - 0.30 * wet * (1 - asphalt) - 0.1 * asphalt + 0.05 * fine, 0.22, 1))


def soviet_concrete():
    """Precast panel concrete: 3 m panels with seams, rust and water streaks running down."""
    n = 1024
    m = noise(n, 5, 4, seed=221)
    fine = noise(n, 7, 40, seed=222)
    y, x = np.mgrid[0:n, 0:n] / n
    seam = np.clip(1 - np.minimum(np.minimum(x, 1 - x), np.minimum(y, 1 - y)) / 0.006, 0, 1)
    streak_cols = np.clip(noise(n, 2, 24, seed=223)[0:1, :] * 2.2 - 1.0, 0, 1)
    streak = streak_cols * (0.4 + 0.6 * (1 - y)) * noise(n, 3, 3, seed=224)
    rust = np.clip(streak_cols * 1.5 - 0.6, 0, 1) * (1 - y) * 0.6
    pits = (noise(n, 6, 64, seed=225) > 0.72).astype(float)
    g = 0.56 + 0.08 * m + 0.05 * fine - 0.18 * streak
    base = np.dstack([g * 0.99, g * 0.99, g * 1.01])
    base = base * (1 - rust[..., None]) + np.array([0.38, 0.24, 0.15]) * rust[..., None]
    base *= (1 - 0.45 * seam - 0.15 * pits)[..., None]
    save("soviet", base)
    save("soviet_n", normal_from_height(fine * 0.35 + m * 0.2 - seam * 0.9 - pits * 0.3, 4.0))
    save("soviet_r", np.clip(0.88 + 0.06 * fine - 0.2 * streak, 0, 1))


def fence_panel():
    """Soviet PO-2 fence panel: raised rhombus relief inside a frame (one 2.4 m panel per tile)."""
    n = 1024
    y, x = np.mgrid[0:n, 0:n] / n
    u, v = (x * 6) % 1, (y * 4) % 1
    d = np.abs(u - 0.5) + np.abs(v - 0.5)
    rhombus = np.clip((0.42 - d) / 0.06, 0, 1)
    frame = np.clip(1 - np.minimum(np.minimum(x, 1 - x), np.minimum(y, 1 - y)) / 0.05, 0, 1)
    m = noise(n, 5, 4, seed=231)
    fine = noise(n, 7, 40, seed=232)
    stain = np.clip(noise(n, 3, 3, seed=233) - 0.45, 0, 1) * (1 - y) * 0.8
    h = rhombus * 0.6 + frame * 0.8 + fine * 0.1
    g = 0.58 + 0.07 * m + 0.04 * fine - 0.2 * stain
    base = np.dstack([g, g * 0.995, g * 0.99]) * (0.92 + 0.08 * h)[..., None]
    save("fence", base)
    save("fence_n", normal_from_height(h, 7.0))
    save("fence_r", np.clip(0.87 + 0.05 * fine, 0, 1))


def steel_paint():
    """Painted steel (greyscale; tinted by material): chipped paint, rust at edges, grime."""
    n = 1024
    m = noise(n, 5, 6, seed=241)
    fine = noise(n, 7, 48, seed=242)
    chips = np.clip((noise(n, 6, 24, seed=243) - 0.70) * 8, 0, 1)
    rust = np.clip((noise(n, 5, 8, seed=244) - 0.68) * 4, 0, 1)
    grime = noise(n, 3, 2, seed=245)
    g = 0.72 + 0.08 * m + 0.04 * fine - 0.12 * grime
    base = np.dstack([g, g, g])
    base = base * (1 - chips[..., None]) + np.array([0.32, 0.33, 0.34]) * chips[..., None]
    base = base * (1 - rust[..., None]) + np.array([0.36, 0.20, 0.10]) * rust[..., None]
    save("steel_paint", base)
    save("steel_paint_n", normal_from_height(fine * 0.2 - chips * 0.4 + m * 0.2, 3.0))
    save("steel_paint_r", np.clip(0.55 + 0.25 * rust + 0.1 * grime - 0.1 * chips, 0, 1))


def ice():
    """Thin ice / frost on concrete (spawn pads, walkway deck): bluish, glossy patches."""
    n = 512
    m = noise(n, 5, 4, seed=251)
    cracks = np.clip(1 - np.abs(noise(n, 5, 10, seed=252) - 0.5) / 0.012, 0, 1)
    frost = noise(n, 7, 32, seed=253)
    glossy = np.clip((m - 0.45) * 3, 0, 1)
    g = 0.62 + 0.10 * m + 0.08 * frost
    base = np.dstack([g * 0.93, g * 0.97, g * 1.02]) * (1 - 0.25 * cracks)[..., None]
    save("ice", base)
    save("ice_n", normal_from_height(frost * 0.2 - cracks * 0.5, 2.5))
    save("ice_r", np.clip(0.75 - 0.5 * glossy + 0.1 * frost, 0.18, 1))


def windows():
    """Window atlas: left half lit (warm interior, curtains, mullions), right half dark glass."""
    w, h = 512, 256
    y, x = np.mgrid[0:h, 0:w] / np.array([h, w])[:, None, None]
    u = (x * 2) % 1
    lit = x < 0.5
    mull = (np.abs(u - 0.5) < 0.025) | (np.abs(y - 0.38) < 0.03) | (u < 0.04) | (u > 0.96) | (y < 0.06) | (y > 0.94)
    warm = np.dstack([0.98 - 0.25 * y, 0.70 - 0.25 * y, 0.38 - 0.15 * y])
    curtain = ((u < 0.18) | (u > 0.82)) & (y > 0.06)
    warm = np.where(curtain[..., None], warm * np.array([0.75, 0.42, 0.30]), warm)
    glass = np.dstack([0.05 + 0.1 * y, 0.07 + 0.1 * y, 0.09 + 0.12 * y])
    img = np.where(lit[..., None], warm, glass)
    img[mull] = (0.08, 0.08, 0.085)
    save("windows", img)


def pine():
    """Pine needles (tiling, opaque: the trees are tiered cones, snow is geometry) and bark."""
    n = 512
    y, x = np.mgrid[0:n, 0:n] / n
    m = noise(n, 5, 8, seed=261)
    fine = noise(n, 7, 64, seed=262)
    strokes = 0.5 + 0.5 * np.sin((x * 90 + y * 30 + m * 10) * np.pi)
    col = tint(m * 0.6 + fine * 0.4, (0.035, 0.085, 0.06), (0.10, 0.19, 0.12)) * (0.8 + 0.25 * strokes)[..., None]
    frost = np.clip((noise(n, 6, 16, seed=264) - 0.68) * 4, 0, 1)
    col = col * (1 - frost[..., None]) + np.array([0.72, 0.76, 0.8]) * frost[..., None]
    save("pine", col)
    save("pine_n", normal_from_height(strokes * 0.3 + fine * 0.3, 3.0))
    rings = noise(n, 5, 16, seed=263)
    bark = tint(rings, (0.18, 0.12, 0.09), (0.33, 0.24, 0.17))
    save("pine_bark", bark)
    save("pine_bark_n", normal_from_height(np.abs(np.sin(x * 40 + rings * 4)), 3.0))


def mountain():
    """Distant ridges: rock strata and snow fields (y up = snow above), tiled every 60 m."""
    n = 1024
    y, x = np.mgrid[0:n, 0:n] / n
    m = noise(n, 6, 4, seed=271)
    gullies = noise(n, 6, 10, seed=273)
    strata = 0.5 + 0.5 * np.sin((y * 6 + x * 2 + m * 4.5) * np.pi)
    snowline = np.clip((m * 0.8 + gullies * 0.35 + strata * 0.1 - 0.5) * 5, 0, 1)
    rock = tint(noise(n, 6, 16, seed=272), (0.20, 0.21, 0.23), (0.36, 0.37, 0.40))
    snowc = np.array([0.88, 0.91, 0.95]) * (0.92 + 0.08 * m)[..., None]
    base = rock * (1 - snowline[..., None]) + snowc * snowline[..., None]
    save("mountain", base)
    save("mountain_n", normal_from_height(m * 0.6 + strata * 0.2, 4.0))


def tarp():
    """Military canvas tarp: coarse cloth with low-contrast weave, creases and grime."""
    n = 512
    y, x = np.mgrid[0:n, 0:n] / n
    m = noise(n, 5, 4, seed=291)
    crease = np.clip(1 - np.abs(noise(n, 4, 3, seed=292) - 0.5) / 0.03, 0, 1)
    weave = 0.5 + 0.12 * (np.sin(x * 2 * np.pi * 48) + np.sin(y * 2 * np.pi * 48))
    g = 0.74 + 0.12 * m - 0.12 * crease
    base = np.dstack([g, g * 0.98, g * 0.9]) * (0.94 + 0.06 * weave)[..., None]
    save("tarp", base)
    save("tarp_n", normal_from_height(m * 0.5 - crease * 0.6 + weave * 0.05, 3.0))


def bulbs():
    """Festive bulb colours (4 x 1 swatches): warm white, amber, muted red, muted green."""
    img = np.zeros((4, 16, 3))
    for i, c in enumerate([(1.0, 0.86, 0.6), (1.0, 0.62, 0.22), (0.95, 0.25, 0.18), (0.35, 0.85, 0.35)]):
        img[:, i * 4:(i + 1) * 4] = c
    Image.fromarray((img * 255).astype(np.uint8), "RGB").resize((64, 16), Image.NEAREST).save(
        os.path.join(OUT, "bulbs.png"))


def pad_marks():
    """Spawn pad paint (RGBA atlas, alpha-tested): 'SPAWN' + 'A' (left) and 'B' (right), worn."""
    w, h = 1024, 512
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    try:
        big = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 300)
        small = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 78)
    except OSError:
        big = small = ImageFont.load_default()
    for i, letter in enumerate("AB"):
        cx = w // 4 + i * w // 2
        d.text((cx, 110), "SPAWN", font=small, fill=(232, 234, 236, 255), anchor="mm")
        d.text((cx, 320), letter, font=big, fill=(232, 234, 236, 255), anchor="mm")
    a = np.array(img).astype(float) / 255
    wear = noise(512, 6, 32, seed=281)
    wear = np.array(Image.fromarray((wear * 255).astype(np.uint8)).resize((w, h))) / 255
    a[..., 3] *= (wear > 0.3).astype(float)
    Image.fromarray((a * 255).astype(np.uint8), "RGBA").save(os.path.join(OUT, "padmarks.png"))


def lightpool(lamps_path):
    """Baked warm light on the ground (emissive, second UV set over the playable rectangle)."""
    L = json.load(open(lamps_path))
    W, D = L["arena"]["width"] + 4, L["arena"]["depth"] + 4
    n = 512
    y, x = np.mgrid[0:n, 0:n] / n
    gx, gz = (x - 0.5) * W, (y - 0.5) * D
    light = np.zeros((n, n, 3))
    for lx, lz, r, power, col in L["lamps"]:
        d2 = (gx - lx) ** 2 + (gz - lz) ** 2
        # Softer, less saturated pools: warm but not orange.
        c = np.array(col) * 0.7 + 0.3
        light += np.exp(-d2 / (r * r))[..., None] * power * 0.55 * c
    save("lightpool", np.clip(light, 0, 0.6))



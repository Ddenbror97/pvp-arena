/** Topic pages are only published when the cluster has enough guides to be useful. */
export const MIN_TOPIC_GUIDES = 3;

export function clusterInfo(name: GuideCluster): ClusterInfo {
  return CLUSTERS.find((c) => c.name === name)!;
}

export function familyOf(slug: string): string[] {
  return groupOf(slug)?.siblings.filter((s) => s !== slug) ?? [];
}

/** The tight subcluster a guide belongs to. Sibling links use this group, not the whole topic. */
export function groupOf(slug: string): { name: string; siblings: string[] } | undefined {
  for (const groups of Object.values(CLUSTER_GROUPS)) {
    for (const g of groups) {
      if (g.slugs.includes(slug)) return { name: g.name, siblings: g.slugs };
    }
  }
  return undefined;
}
